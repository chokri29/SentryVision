@app.post("/analyze", response_model=AuditResponse)
def analyze_contract(request: Request, payload: AuditRequest):
    enforce_rate_limit(get_client_ip(request))

    code = payload.solidity_code
    if not code.strip():
        raise HTTPException(status_code=400, detail="Please provide Solidity code to analyze.")
    if len(code) > MAX_CODE_CHARS:
        raise HTTPException(status_code=413, detail="Solidity input exceeds the maximum allowed length.")

    try:
        model_client = client._ensure()
    except RuntimeError as exc:
        logger.error("Configuration error: %s", exc)
        raise HTTPException(status_code=500, detail="Server is not configured correctly.") from exc

    slither_findings: list = []
    slither_error: str | None = None
    original_high_medium_checks = None

    if ENABLE_SLITHER:
        slither_result = run_slither(code, payload.contract_name)
        if slither_result is None:
            slither_error = "Slither unavailable"
        elif not slither_result.get("success"):
            slither_error = slither_result.get("error") or "Slither failed"
            logger.info("Slither fallback to Muse-only: %s", slither_error)
        else:
            slither_findings = (
                slither_result.get("filtered_detectors")
                or slither_result.get("detectors")
                or []
            )
            original_high_medium_checks = sorted({
                d["check"]
                for d in (slither_result.get("detectors") or [])
                if d.get("impact") in {"Critical", "High", "Medium"} and d.get("check")
            })
            logger.info("Slither: %s findings", len(slither_findings))
    else:
        slither_error = "Slither disabled"

    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {
            "role": "user",
            "content": USER_TEMPLATE.format(
                code=code, slither=format_slither_for_prompt(slither_findings)
            ),
        },
    ]

    for attempt in range(2):
        try:
            kwargs = {
                "model": MODEL_NAME,
                "messages": messages,
                "temperature": 0.2 if attempt == 0 else 0.0,
                "max_tokens": MAX_OUTPUT_TOKENS,
                "timeout": REQUEST_TIMEOUT_SECONDS,
            }
            if USE_JSON_MODE:
                kwargs["response_format"] = {"type": "json_object"}

            response = model_client.chat.completions.create(**kwargs)
            raw_content = response.choices[0].message.content
            result = parse_and_validate_model_output(raw_content)

            findings = verify_patches(
                result.findings,
                original_code=code,
                original_high_medium_checks=original_high_medium_checks,
            )

            return AuditResponse(
                summary=result.summary,
                findings=findings,
                meta={
                    "model": MODEL_NAME,
                    "reasoning_repaired": attempt > 0,
                    "slither_available": is_slither_available(),
                    "slither_enabled": ENABLE_SLITHER,
                    "slither_findings_count": len(slither_findings),
                    "slither_error": slither_error,
                    "f1_ran": slither_error is None,
                    "pipeline_label": (
                        "F1 Slither → F2 Muse → F3 verify"
                        if slither_error is None
                        else "F2 only (static analysis unavailable)"
                    ),
                    "patches_verified_count": sum(
                        1 for f in findings if getattr(f, "patch_verified", False)
                    ),
                    "patches_proposed_count": sum(
                        1
                        for f in findings
                        if getattr(f, "patched_code", None)
                        and str(getattr(f, "patched_code")).strip()
                    ),
                    "patches_failed_count": sum(
                        1
                        for f in findings
                        if getattr(f, "patch_verification_status", None) == "failed"
                    ),
                },
            )

        except (TypeError, ValueError, ValidationError, json.JSONDecodeError) as exc:
            logger.warning("Invalid model output (attempt %d): %s", attempt + 1, exc)
            if attempt == 0:
                messages = messages + [
                    {
                        "role": "assistant",
                        "content": raw_content if "raw_content" in locals() else "",
                    },
                    {
                        "role": "user",
                        "content": REPAIR_TEMPLATE.format(
                            error=str(exc)[:500],
                            bad_output=(
                                raw_content[:4000]
                                if "raw_content" in locals() and raw_content
                                else ""
                            ),
                        ),
                    },
                ]
        except Exception:
            logger.exception("Model call failed (attempt %d)", attempt + 1)
            break

    raise HTTPException(
        status_code=502, detail="Analysis could not be validated; please try again."
    )


