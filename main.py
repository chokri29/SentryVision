def verify_patches(findings: list, original_code: Optional[str] = None, original_high_medium_checks: Optional[Iterable[str]] = None, allow_verification: bool = True, original_detector_checks: Optional[Iterable[str]] = None):
    if not allow_verification:
        for f in findings:
            f.patch_verified = False
            f.retry_recommended = False
            f.retry_available = False
            if (f.patched_code or "").strip():
                f.patch_verification_status = "not_checked"
                f.verification_error_kind = None
                f.patch_failure_kind = "verification_skipped"
                f.patch_verification_details = MODEL_ONLY_DETAILS
                f.remaining_checks = []
            else:
                f.patch_verification_status = "not_checked"
                f.verification_error_kind = None
                c = classify_patch_verification(patched_code=f.patched_code, original_code=original_code, patch_verification_status=f.patch_verification_status, verification_error_kind=f.verification_error_kind, remaining_checks=[], original_high_medium_checks=original_high_medium_checks, retry_count=f.retry_count)
                f.patch_failure_kind, f.retry_recommended, f.retry_available = c["patch_failure_kind"], False, False
                f.remaining_checks = []
        return findings
    has_any_patch = any((f.patched_code or "").strip() for f in findings)
    if not has_any_patch:
        for f in findings:
            f.patch_verification_status = "not_checked"
            f.verification_error_kind = None
            c = classify_patch_verification(patched_code=f.patched_code, original_code=original_code, patch_verification_status=f.patch_verification_status, verification_error_kind=f.verification_error_kind, remaining_checks=list(f.remaining_checks or []), original_high_medium_checks=original_high_medium_checks, retry_count=f.retry_count)
            f.patch_failure_kind, f.retry_recommended, f.retry_available = c["patch_failure_kind"], c["retry_recommended"], c["retry_available"]
            f.remaining_checks = []
        return findings
    slither_ready = ENABLE_SLITHER
    verified_count = 0
    for f in findings:
        code = (f.patched_code or "").strip()
        if not code:
            f.patch_verification_status = "not_checked"
            f.verification_error_kind = None
            c = classify_patch_verification(patched_code=f.patched_code, original_code=original_code, patch_verification_status=f.patch_verification_status, verification_error_kind=f.verification_error_kind, remaining_checks=[], original_high_medium_checks=original_high_medium_checks, retry_count=f.retry_count)
            f.patch_failure_kind, f.retry_recommended, f.retry_available = c["patch_failure_kind"], c["retry_recommended"], c["retry_available"]
            continue
        if original_code is not None and code == original_code.strip():
            f.patch_verification_status = "not_checked"
            f.verification_error_kind = None
            f.patch_verification_details = "Patch identical to original — skipped F3."
            c = classify_patch_verification(patched_code=f.patched_code, original_code=original_code, patch_verification_status=f.patch_verification_status, verification_error_kind=None, remaining_checks=[], original_high_medium_checks=original_high_medium_checks, retry_count=f.retry_count)
            f.patch_failure_kind, f.retry_recommended, f.retry_available = c["patch_failure_kind"], c["retry_recommended"], c["retry_available"]
            continue
        if not slither_ready:
            f.patch_verification_status = "slither_unavailable"
            f.verification_error_kind = "slither_unavailable"
            c = classify_patch_verification(patched_code=f.patched_code, original_code=original_code, patch_verification_status=f.patch_verification_status, verification_error_kind=f.verification_error_kind, remaining_checks=[], original_high_medium_checks=original_high_medium_checks, retry_count=f.retry_count)
            f.patch_failure_kind, f.retry_recommended, f.retry_available = c["patch_failure_kind"], c["retry_recommended"], c["retry_available"]
            continue
        if verified_count >= MAX_PATCH_VERIFICATIONS:
            f.patch_verification_status = "not_checked"
            f.patch_verification_details = "Verification capped for this request."
            c = classify_patch_verification(patched_code=f.patched_code, original_code=original_code, patch_verification_status="not_checked", verification_error_kind=None, remaining_checks=[], original_high_medium_checks=original_high_medium_checks, retry_count=f.retry_count)
            f.patch_failure_kind, f.retry_recommended, f.retry_available = c["patch_failure_kind"], c["retry_recommended"], c["retry_available"]
            continue
        if original_code:
            ratio = len(code) / max(len(original_code.strip()), 1)
            if ratio < 0.3 or ratio > 3.0:
                f.patch_verification_status = "not_checked"
                f.patch_verification_details = "Patch length abnormal vs original — skipped F3."
                c = classify_patch_verification(patched_code=f.patched_code, original_code=original_code, patch_verification_status="not_checked", verification_error_kind=None, remaining_checks=[], original_high_medium_checks=original_high_medium_checks, retry_count=f.retry_count)
                f.patch_failure_kind, f.retry_recommended, f.retry_available = c["patch_failure_kind"], c["retry_recommended"], c["retry_available"]
                continue
        result = verify_patch(code, target_checks=list(original_detector_checks) if original_detector_checks is not None else None, original_entry_points=public_entry_points(original_code) if original_code else None, original_code=original_code)
        verified_count += 1
        f.patch_verified = result.get("patch_verified", False)
        f.patch_verification_status = result.get("patch_verification_status", "failed")
        details = result.get("patch_verification_details") or ""
        if "Traceback" in details or len(details) > 280:
            details = (details.split("Traceback")[0].strip() or "Could not compile/verify patch with Slither (solc error).")[:280]
        f.patch_verification_details = details
        f.remaining_checks = list(result.get("remaining_checks") or [])
        f.behaviour_lite_passed = bool(result.get("behaviour_lite_passed", False))
        f.gutted_functions = list(result.get("gutted_functions") or [])
        f.unresolved_imports = list(result.get("unresolved_imports") or [])
        f.verification_error_kind = result.get("verification_error_kind") or None
        c = classify_patch_verification(patched_code=f.patched_code, original_code=original_code, patch_verification_status=f.patch_verification_status, verification_error_kind=f.verification_error_kind, remaining_checks=f.remaining_checks, original_high_medium_checks=original_high_medium_checks, retry_count=f.retry_count, surface_removed=result.get("surface_removed") or [], gutted_functions=result.get("gutted_functions") or [])
        f.patch_failure_kind, f.retry_recommended, f.retry_available = c["patch_failure_kind"], c["retry_recommended"], c["retry_available"]
    return findings


def verify_consolidated_patch(code: Optional[str], original_code: str, original_checks: Optional[Iterable[str]], allow_verification: bool, change_summary: Optional[str] = None, retry_count: int = 0, original_high_medium_checks: Optional[Iterable[str]] = None) -> ConsolidatedPatch:
    patch = (code or "").strip() or None
    result = ConsolidatedPatch(code=patch, change_summary=change_summary, diff=_unified_diff(original_code, patch or ""))
    if not patch:
        result.failure_kind = "model_no_patch"
        return result
    if patch == original_code.strip():
        result.failure_kind = "patch_identical"
        result.verification_details = "Patch identical to original — skipped F3."
        return result
    if not allow_verification:
        result.failure_kind = "verification_skipped"
        result.verification_details = MODEL_ONLY_DETAILS
        return result
    if not ENABLE_SLITHER:
        result.verification_status = "slither_unavailable"
        result.failure_kind = "infra_error"
        result.verification_details = "Slither disabled; patch is not verified."
        return result
    ratio = len(patch) / max(len(original_code.strip()), 1)
    if ratio < 0.3 or ratio > 3.0:
        result.failure_kind = "verification_skipped"
        result.verification_details = "Patch length abnormal vs original — skipped F3."
        return result
    checked = verify_patch(patch, target_checks=list(original_checks) if original_checks is not None else None, original_entry_points=public_entry_points(original_code), original_code=original_code)
    result.patch_verified = bool(checked.get("patch_verified"))
    result.verification_status = checked.get("patch_verification_status", "failed")
    result.verification_details = (checked.get("patch_verification_details") or "")[:280]
    result.remaining_checks = list(checked.get("remaining_checks") or [])
    result.behaviour_lite_passed = bool(checked.get("behaviour_lite_passed"))
    result.failure_kind = classify_patch_verification(
        patched_code=patch, original_code=original_code,
        patch_verification_status=result.verification_status,
        verification_error_kind=checked.get("verification_error_kind"),
        remaining_checks=result.remaining_checks,
        original_high_medium_checks=original_high_medium_checks if original_high_medium_checks is not None else original_checks, retry_count=retry_count,
        surface_removed=checked.get("surface_removed") or [],
        gutted_functions=checked.get("gutted_functions") or [],
    )["patch_failure_kind"]
    result.retry_available = bool(not result.patch_verified and result.failure_kind in {"still_vulnerable","compile_failed","regression_introduced","surface_removed","gutted_function"} and retry_count < MAX_PATCH_RETRIES and RETRY_API_KEY)
    return result


