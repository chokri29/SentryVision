def _prune_analysis_store(now: Optional[float] = None) -> None:
    now = time.time() if now is None else now
    expired = [aid for aid, row in analysis_store.items() if now - float(row.get("created_at", 0)) > ANALYSIS_TTL_SECONDS]
    for aid in expired:
        analysis_store.pop(aid, None)
    if len(analysis_store) <= ANALYSIS_STORE_MAX:
        return
    ordered = sorted(analysis_store.items(), key=lambda kv: float(kv[1].get("created_at", 0)))
    for aid, _ in ordered[: len(analysis_store) - ANALYSIS_STORE_MAX]:
        analysis_store.pop(aid, None)


