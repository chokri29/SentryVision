RATE_LIMIT_WINDOW_SECONDS = 60
MAX_REQUESTS_PER_WINDOW = 6
request_history: dict[str, deque[float]] = defaultdict(deque)


def enforce_rate_limit(client_ip: str) -> None:
    now = time.monotonic()
    history = request_history[client_ip]
    while history and now - history[0] > RATE_LIMIT_WINDOW_SECONDS:
        history.popleft()
    if len(history) >= MAX_REQUESTS_PER_WINDOW:
        raise HTTPException(status_code=429, detail="Rate limit exceeded. Please try again later.")
    history.append(now)


def get_client_ip(request: Request) -> str:
    forwarded = request.headers.get("x-forwarded-for")
    if forwarded:
        return forwarded.split(",")[0].strip()
    return request.client.host if request.client else "unknown"


def format_slither_for_prompt(detectors: list) -> str:
    if not detectors:
        return "No Slither findings provided. Rely on source code analysis only."
    slim = [
        {
            "check": d.get("check"),
            "impact": d.get("impact"),
            "confidence": d.get("confidence"),
            "description": (d.get("description") or "")[:500],
            "lines": d.get("lines", []),
        }
        for d in detectors[:20]
    ]
    return json.dumps(slim, indent=2, default=str)[:8000]


def classify_patch_verification(
    patched_code: Optional[str],
    original_code: Optional[str],
    patch_verification_status: str,
    verification_error_kind: Optional[str],
    remaining_checks: list[str],
    original_high_medium_checks: Optional[Iterable[str]],
    retry_count: int,
):
    if patched_code is None or not patched_code.strip():
        patch_failure_kind = "model_no_patch"
        retry_recommended = False
    elif original_code is not None and patched_code.strip() == original_code.strip():
        patch_failure_kind = "patch_identical"
        retry_recommended = False
    elif patch_verification_status == "slither_unavailable" or verification_error_kind in {
        "slither_unavailable",
        "timeout",
        "invalid_output",
        "execution_error",
    }:
        patch_failure_kind = "infra_error"
        retry_recommended = False
    elif verification_error_kind == "compile_failed":
        patch_failure_kind = "compile_failed"
        retry_recommended = True
    elif patch_verification_status == "verified":
        patch_failure_kind = None
        retry_recommended = False
    elif patch_verification_status == "not_checked":
        patch_failure_kind = "verification_skipped"
        retry_recommended = False
    elif patch_verification_status == "failed":
        checks = list(remaining_checks or [])
        baseline = set(original_high_medium_checks or []) if original_high_medium_checks is not None else None
        if baseline is not None and checks and all(check not in baseline for check in checks):
            patch_failure_kind = "regression_introduced"
            retry_recommended = True
        else:
            patch_failure_kind = "still_vulnerable"
            retry_recommended = True
    else:
        patch_failure_kind = "still_vulnerable"
        retry_recommended = True

    retry_available = retry_recommended and retry_count < MAX_PATCH_RETRIES
    return {
        "patch_failure_kind": patch_failure_kind,
        "retry_recommended": retry_recommended,
        "retry_available": retry_available,
    }


def verify_patches(findings: list[Finding], original_code: Optional[str] = None,
                   original_high_medium_checks: Optional[Iterable[str]] = None):
    """F3 — only run Slither on full proposed patches (skip when Muse returned none)."""
    has_any_patch = any((f.patched_code or "").strip() for f in findings)
    if not has_any_patch:
        for f in findings:
            f.patch_verification_status = "not_checked"
            f.verification_error_kind = None
            classification = classify_patch_verification(
                patched_code=f.patched_code,
                original_code=original_code,
                patch_verification_status=f.patch_verification_status,
                verification_error_kind=f.verification_error_kind,
                remaining_checks=list(f.remaining_checks or []),
                original_high_medium_checks=original_high_medium_checks,
                retry_count=f.retry_count,
            )
            f.patch_failure_kind = classification["patch_failure_kind"]
            f.retry_recommended = classification["retry_recommended"]
            f.retry_available = classification["retry_available"]
            f.remaining_checks = []
        return findings

    slither_ready = ENABLE_SLITHER and is_slither_available()
    verified_count = 0

    for f in findings:
        code = (f.patched_code or "").strip()
        if not code:
            f.patch_verification_status = "not_checked"
            f.verification_error_kind = None
            classification = classify_patch_verification(
                patched_code=f.patched_code,
                original_code=original_code,
                patch_verification_status=f.patch_verification_status,
                verification_error_kind=f.verification_error_kind,
                remaining_checks=list(f.remaining_checks or []),
                original_high_medium_checks=original_high_medium_checks,
                retry_count=f.retry_count,
            )
            f.patch_failure_kind = classification["patch_failure_kind"]
            f.retry_recommended = classification["retry_recommended"]
            f.retry_available = classification["retry_available"]
            f.remaining_checks = []
            continue

        if original_code is not None and code.strip() == original_code.strip():
            f.patch_verification_status = "not_checked"
            f.verification_error_kind = None
            classification = classify_patch_verification(
                patched_code=f.patched_code,
                original_code=original_code,
                patch_verification_status=f.patch_verification_status,
                verification_error_kind=f.verification_error_kind,
                remaining_checks=list(f.remaining_checks or []),
                original_high_medium_checks=original_high_medium_checks,
                retry_count=f.retry_count,
            )
            f.patch_failure_kind = classification["patch_failure_kind"]
            f.retry_recommended = classification["retry_recommended"]
            f.retry_available = classification["retry_available"]
            f.remaining_checks = []
            continue

        if "pragma solidity" not in code or "contract " not in code:
            f.patch_verified = False
            f.patch_verification_status = "not_checked"
            f.patch_verification_details = "Patch is a code snippet, not a full contract. Slither verification skipped."
            f.verification_error_kind = "verification_skipped"
            classification = classify_patch_verification(
                patched_code=f.patched_code,
                original_code=original_code,
                patch_verification_status=f.patch_verification_status,
                verification_error_kind=f.verification_error_kind,
                remaining_checks=list(f.remaining_checks or []),
                original_high_medium_checks=original_high_medium_checks,
                retry_count=f.retry_count,
            )
            f.patch_failure_kind = classification["patch_failure_kind"]
            f.retry_recommended = classification["retry_recommended"]
            f.retry_available = classification["retry_available"]
            f.remaining_checks = []
            continue

        if not slither_ready:
            f.patch_verified = False
            f.patch_verification_status = "slither_unavailable"
            f.patch_verification_details = "Patch generated by Muse Spark, awaiting Slither re-verification."
            f.verification_error_kind = "slither_unavailable"
            classification = classify_patch_verification(
                patched_code=f.patched_code,
                original_code=original_code,
                patch_verification_status=f.patch_verification_status,
                verification_error_kind=f.verification_error_kind,
                remaining_checks=list(f.remaining_checks or []),
                original_high_medium_checks=original_high_medium_checks,
                retry_count=f.retry_count,
            )
            f.patch_failure_kind = classification["patch_failure_kind"]
            f.retry_recommended = classification["retry_recommended"]
            f.retry_available = classification["retry_available"]
            f.remaining_checks = []
            continue

        if verified_count >= MAX_PATCH_VERIFICATIONS:
            f.patch_verified = False
            f.patch_verification_status = "not_checked"
            f.patch_verification_details = "Patch proposed; Slither re-check skipped to keep demo latency low."
            f.verification_error_kind = "verification_skipped"
            classification = classify_patch_verification(
                patched_code=f.patched_code,
                original_code=original_code,
                patch_verification_status=f.patch_verification_status,
                verification_error_kind=f.verification_error_kind,
                remaining_checks=list(f.remaining_checks or []),
                original_high_medium_checks=original_high_medium_checks,
                retry_count=f.retry_count,
            )
            f.patch_failure_kind = classification["patch_failure_kind"]
            f.retry_recommended = classification["retry_recommended"]
            f.retry_available = classification["retry_available"]
            f.remaining_checks = []
            continue

        result = verify_patch(code)
        verified_count += 1
        f.patch_verified = result.get("patch_verified", False)
        f.patch_verification_status = result.get("patch_verification_status", "failed")
        details = result.get("patch_verification_details") or ""
        if "Traceback" in details or len(details) > 280:
            details = details.split("Traceback")[0].strip() or "Could not compile/verify patch with Slither (solc error)."
            details = details[:280]
        f.patch_verification_details = details
        f.remaining_checks = list(result.get("remaining_checks") or [])
        f.verification_error_kind = result.get("verification_error_kind") or None
        classification = classify_patch_verification(
            patched_code=f.patched_code,
            original_code=original_code,
            patch_verification_status=f.patch_verification_status,
            verification_error_kind=f.verification_error_kind,
            remaining_checks=f.remaining_checks,
            original_high_medium_checks=original_high_medium_checks,
            retry_count=f.retry_count,
        )
        f.patch_failure_kind = classification["patch_failure_kind"]
        f.retry_recommended = classification["retry_recommended"]
        f.retry_available = classification["retry_available"]

    return findings


def extract_json_text(raw: str) -> str:
    text = raw.strip()
    text = re.sub(r"<think>.*?</think>", "", text, flags=re.DOTALL | re.IGNORECASE).strip()
    if "<think>" in text.lower():
        text = re.split(r"<think>", text, flags=re.IGNORECASE)[-1].strip()
    if "</think>" in text:
        text = text.split("</think>")[-1].strip()
    if "</reasoning>" in text:
        text = text.split("</reasoning>")[-1].strip()

    text = re.sub(r"^```(?:json)?\s*|\s*```$", "", text, flags=re.IGNORECASE).strip()
    start, end = text.find("{"), text.rfind("}")
    if start == -1 or end <= start:
        raise ValueError("No JSON object found in model output")
    return text[start : end + 1]


def parse_and_validate_model_output(raw: str) -> LLMOutput:
    if not raw or not isinstance(raw, str):
        raise ValueError("Model returned no content")
    return LLMOutput.model_validate(json.loads(extract_json_text(raw)))


