def _unified_diff(original: str, patched: str, max_lines: int = 120) -> str:
    lines = list(difflib.unified_diff((original or "").splitlines(), (patched or "").splitlines(), fromfile="original.sol", tofile="failed_patch.sol", lineterm=""))
    if not lines:
        return "(no diff — patch identical or empty)"
    if len(lines) > max_lines:
        lines = lines[:max_lines] + [f"... ({len(lines) - max_lines} more diff lines truncated)"]
    return "\n".join(lines)


def _finding_retry_targets(findings: list) -> list:
    out = []
    for i, f in enumerate(findings):
        if isinstance(f, dict):
            recommended, available, count = bool(f.get("retry_recommended")), bool(f.get("retry_available")), int(f.get("retry_count") or 0)
            row = f
        else:
            recommended, available, count = bool(getattr(f, "retry_recommended", False)), bool(getattr(f, "retry_available", False)), int(getattr(f, "retry_count", 0) or 0)
            row = f.model_dump() if hasattr(f, "model_dump") else dict(f)
        if recommended and available and count < MAX_PATCH_RETRIES:
            out.append((i, row))
    return out


def extract_json_text(raw: str) -> str:
    text = raw.strip()
    text = re.sub(r"<think>.*?</think>", "", text, flags=re.DOTALL | re.IGNORECASE).strip()
    if "<think>" in text.lower():
        text = re.split(r"<think>", text, flags=re.IGNORECASE)[-1].strip()
    if "</think>" in text:
        text = text.split("</think>")[-1].strip()
    if "</reasoning>" in text:
        text = text.split("</reasoning>")[-1].strip()
    fence = re.search(r"```(?:json)?\s*([\s\S]*?)```", text, re.IGNORECASE)
    if fence:
        text = fence.group(1).strip()
    start, end = text.find("{"), text.rfind("}")
    if start != -1 and end != -1 and end > start:
        text = text[start:end + 1]
    return text


