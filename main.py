class Finding(BaseModel):
    title: str
    severity: Literal["Critical", "High", "Medium", "Low", "Info"]
    what_happens: str
    why_it_matters: str
    what_to_do: str
    mermaid_diagram: str
    patched_code: Optional[str] = None

    patch_verified: bool = False
    patch_verification_status: Literal[
        "verified", "failed", "not_checked", "slither_unavailable"
    ] = "not_checked"
    patch_verification_details: Optional[str] = None
    patch_failure_kind: Optional[Literal[
        "still_vulnerable",
        "compile_failed",
        "regression_introduced",
        "model_no_patch",
        "patch_identical",
        "infra_error",
        "verification_skipped",
    ]] = None
    remaining_checks: list[str] = Field(default_factory=list)
    verification_error_kind: Optional[str] = None
    retry_count: int = 0
    retry_available: bool = False
    retry_recommended: bool = False
    previous_patched_code: Optional[str] = None
    previous_patch_verification_status: Optional[str] = None
    previous_patch_failure_kind: Optional[str] = None
    retry_change_summary: Optional[str] = None

    @field_validator("severity", mode="before")
    @classmethod
    def normalize_severity(cls, value):
        if isinstance(value, str):
            v = value.strip().capitalize()
            return v if v in ["Critical", "High", "Medium", "Low", "Info"] else "Info"
        return value

    @field_validator("mermaid_diagram", mode="before")
    @classmethod
    def clean_mermaid(cls, value):
        if isinstance(value, str):
            return (
                value.removeprefix("```mermaid")
                .removeprefix("```")
                .removesuffix("```")
                .strip()
            )
        return value


