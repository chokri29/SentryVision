def format_slither_for_prompt(detectors: list) -> str:
    if not detectors:
        return "(no Slither findings)"
    lines = []
    for d in detectors[:30]:
        check = d.get("check") or d.get("name") or "unknown"
        impact = d.get("impact") or "?"
        confidence = d.get("confidence") or "?"
        source_lines = d.get("lines") or []
        line_label = ", ".join(str(n) for n in source_lines[:12]) if source_lines else "not mapped"
        desc = (d.get("description") or "").strip().replace("\n", " ")
        lines.append(f"- [{impact}/{confidence}] {check} (lines: {line_label}): {desc[:220]}")
    return "\n".join(lines)

def classify_patch_verification(*, patched_code: Optional[str], original_code: Optional[str], patch_verification_status: str, verification_error_kind: Optional[str], remaining_checks: Optional[list], original_high_medium_checks: Optional[Iterable[str]], retry_count: int, surface_removed: Optional[Iterable[str]] = None, gutted_functions: Optional[Iterable[str]] = None) -> dict:
    code = (patched_code or "").strip()
    if not code:
        patch_failure_kind, retry_recommended = "model_no_patch", False
    elif original_code is not None and code == original_code.strip():
        patch_failure_kind, retry_recommended = "patch_identical", False
    elif verification_error_kind in {"slither_unavailable", "timeout", "execution_error", "unsupported_import"}:
        patch_failure_kind, retry_recommended = "infra_error", False
    elif verification_error_kind == "compile_failed":
        patch_failure_kind, retry_recommended = "compile_failed", True
    elif patch_verification_status == "verified":
        patch_failure_kind, retry_recommended = None, False
    elif patch_verification_status == "not_checked":
        patch_failure_kind, retry_recommended = "verification_skipped", False
    elif patch_verification_status == "failed":
        checks = list(remaining_checks or [])
        removed = [name for name in (surface_removed or []) if name]
        baseline = set(original_high_medium_checks or []) if original_high_medium_checks is not None else None
        if checks and baseline is not None and any(c not in baseline for c in checks):
            # Any newly introduced Critical/High/Medium detector is a regression,
            # even when one or more baseline findings remain unresolved.
            patch_failure_kind, retry_recommended = "regression_introduced", True
        elif checks:
            patch_failure_kind, retry_recommended = "still_vulnerable", True
        elif list(gutted_functions or []):
            patch_failure_kind, retry_recommended = "gutted_function", True
        elif removed:
            patch_failure_kind, retry_recommended = "surface_removed", True
        else:
            patch_failure_kind, retry_recommended = "still_vulnerable", True
    else:
        patch_failure_kind, retry_recommended = "still_vulnerable", True
    return {"patch_failure_kind": patch_failure_kind, "retry_recommended": retry_recommended, "retry_available": retry_recommended and retry_count < MAX_PATCH_RETRIES}


MODEL_ONLY_DETAILS = "Model only — Slither did not analyze the original contract, so this patch is not verified."
