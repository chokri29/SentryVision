def store_analysis(*, analysis_id: str, original_code: str, contract_name: str, findings: list, original_high_medium_checks: Optional[list], slither_error: Optional[str], model_used: str, summary: str, original_detector_checks: Optional[list] = None, retry_count: int = 0) -> None:
    _prune_analysis_store()
    serialized = [f.model_dump() if hasattr(f, "model_dump") else dict(f) for f in findings]
    prev = get_analysis(analysis_id) or {}
    row = {
        "created_at": prev.get("created_at", time.time()),
        "original_code": original_code,
        "contract_name": contract_name,
        "summary": summary,
        "findings": serialized,
        "original_high_medium_checks": list(original_high_medium_checks or []),
        "original_detector_checks": list(original_detector_checks or []),
        "slither_error": slither_error,
        "model_used": model_used,
        "retry_count": int(retry_count),
    }
    store = _redis()
    if store:
        try:
            store.setex(f"sv:analysis:{analysis_id}", ANALYSIS_TTL_SECONDS, json.dumps(row))
        except Exception as exc:
            logger.exception("Could not persist shared analysis state")
            raise HTTPException(status_code=503, detail="Shared retry storage is temporarily unavailable.") from exc
    elif REQUIRE_SHARED_STORAGE:
        raise HTTPException(status_code=503, detail="Shared retry storage is not configured. Please try again later.")
    else:
        analysis_store[analysis_id] = row


def get_analysis(analysis_id: str) -> Optional[dict[str, Any]]:
    try:
        store = _redis()
        if store:
            raw = store.get(f"sv:analysis:{analysis_id}")
            return json.loads(raw) if raw else None
    except Exception as exc:
        logger.exception("Could not retrieve shared analysis state")
        if REQUIRE_SHARED_STORAGE:
            raise HTTPException(status_code=503, detail="Shared retry storage is temporarily unavailable.") from exc
        return None
    _prune_analysis_store()
    row = analysis_store.get(analysis_id)
    if not row or time.time() - float(row.get("created_at", 0)) > ANALYSIS_TTL_SECONDS:
        analysis_store.pop(analysis_id, None)
        return None
    return row


