@app.post("/analyze", response_model=AuditResponse)
def analyze_contract(request: Request, payload: AuditRequest):
    enforce_rate_limit(get_client_ip(request))
    code = payload.solidity_code
    if not code.strip():
        raise HTTPException(status_code=400, detail="Please provide Solidity code to analyze.")
    if len(code) > MAX_CODE_CHARS:
        raise HTTPException(status_code=413, detail="Solidity input exceeds the maximum allowed length.")
    try:
        model_client = client._ensure()
    except RuntimeError as exc:
        raise HTTPException(status_code=500, detail="Server is not configured correctly.") from exc
    slither_findings, slither_error, original_high_medium_checks, original_detector_checks = [], None, None, None
    if ENABLE_SLITHER:
        slither_result = run_slither(code, payload.contract_name)
        if slither_result is None:
            slither_error = "Slither unavailable"
        elif not slither_result.get("success"):
            slither_error = slither_result.get("error") or "Slither failed"
        else:
            slither_findings = slither_result.get("filtered_detectors") or slither_result.get("detectors") or []
            original_high_medium_checks = sorted({d["check"] for d in (slither_result.get("detectors") or []) if d.get("impact") in {"Critical", "High", "Medium"} and d.get("check")})
            original_detector_checks = sorted(
                {d["check"] for d in (slither_result.get("filtered_detectors") or []) if d.get("check")}
                | set(original_high_medium_checks)
            )
    else:
        slither_error = "Slither disabled"
    messages = [{"role": "system", "content": SYSTEM_PROMPT}, {"role": "user", "content": USER_TEMPLATE.format(code=code, slither=format_slither_for_prompt(slither_findings))}]
    for attempt in range(2):
        try:
            kwargs = {"model": MODEL_NAME, "messages": messages, "temperature": 0.2 if attempt == 0 else 0.0, "max_tokens": MAX_OUTPUT_TOKENS, "timeout": REQUEST_TIMEOUT_SECONDS}
            if USE_JSON_MODE:
                kwargs["response_format"] = {"type": "json_object"}
            completion = model_client.chat.completions.create(**kwargs)
            raw_content = completion.choices[0].message.content or ""
            result = parse_and_validate_model_output(raw_content)
            findings = result.findings
            detector_map = {d.get("check"): d for d in slither_findings if d.get("check")}
            for finding in findings:
                detector = detector_map.get(finding.slither_check or "")
                if detector:
                    finding.grounding_status = "grounded"
                    finding.slither_check = detector["check"]
                    finding.slither_impact = detector.get("impact")
                    finding.slither_confidence = detector.get("confidence")
                    finding.slither_lines = list(detector.get("lines") or [])
                    finding.severity = {"Informational": "Info", "Optimization": "Info"}.get(detector.get("impact"), detector.get("impact", "Info"))
                else:
                    finding.grounding_status = "ungrounded" if slither_error is None else "f1_unavailable"
                    finding.slither_check = None
                    finding.slither_impact = None
                    finding.slither_confidence = None
                    finding.slither_lines = []
                finding.patched_code = None
                finding.patch_verified = False
                finding.patch_verification_status = "not_checked"
                finding.retry_available = False
                finding.retry_recommended = False
            consolidated = verify_consolidated_patch(result.consolidated_patch, code, original_detector_checks, ENABLE_SLITHER, result.patch_change_summary, original_high_medium_checks=original_high_medium_checks)
            analysis_id = new_analysis_id()
            store_analysis(analysis_id=analysis_id, original_code=code, contract_name=payload.contract_name, findings=findings, original_high_medium_checks=original_high_medium_checks, original_detector_checks=original_detector_checks, slither_error=slither_error, model_used=MODEL_NAME, summary=result.summary)
            analysis_row = get_analysis(analysis_id) or {}
            analysis_row["consolidated_patch"] = consolidated.model_dump()
            update_analysis(analysis_id, analysis_row)
            any_retry = consolidated.retry_available
            return AuditResponse(summary=result.summary, findings=findings, consolidated_patch=consolidated, meta={
                "analysis_id": analysis_id, "model": MODEL_NAME, "reasoning_repaired": attempt > 0,
                "slither_available": is_slither_available(), "slither_enabled": ENABLE_SLITHER,
                "slither_findings_count": len(slither_findings), "slither_error": slither_error,
                "f1_ran": slither_error is None,
                "pipeline_label": "F1 Slither → F2 Muse → F3 verify" if slither_error is None else MODEL_ONLY_PIPELINE,
                "patches_verified_count": int(consolidated.patch_verified),
                "patches_proposed_count": int(bool(consolidated.code)),
                "patches_failed_count": int(consolidated.verification_status == "failed"),
                "retry_count": 0, "max_patch_retries": MAX_PATCH_RETRIES, "retry_available": any_retry,
            })
        except (TypeError, ValueError, ValidationError, json.JSONDecodeError) as exc:
            if attempt == 0:
                messages = messages + [{"role": "assistant", "content": raw_content if "raw_content" in locals() else ""}, {"role": "user", "content": REPAIR_TEMPLATE.format(error=str(exc)[:500], bad_output=(raw_content[:4000] if "raw_content" in locals() and raw_content else ""))}]
        except Exception:
            logger.exception("Model call failed (attempt %d)", attempt + 1)
            break
    raise HTTPException(status_code=502, detail="Analysis could not be validated; please try again.")


@app.post("/analyze/{analysis_id}/retry-patch", response_model=AuditResponse)
def retry_patch(analysis_id: str, request: Request):
    enforce_rate_limit(get_client_ip(request))
    row = get_analysis(analysis_id)
    if not row:
        raise HTTPException(status_code=404, detail="This retry has expired or is no longer available. Please run the analysis again.")
    retry_count = int(row.get("retry_count") or 0)
    if retry_count >= MAX_PATCH_RETRIES:
        raise HTTPException(status_code=400, detail="Retry exhausted for this analysis. Review manually.")
    findings_data = list(row.get("findings") or [])
    previous = row.get("consolidated_patch") or {}
    if not previous.get("retry_available"):
        raise HTTPException(status_code=400, detail="The consolidated patch is not eligible for retry.")
    try:
        model_client = retry_client._ensure()
    except RuntimeError as exc:
        logger.warning("Muse Wonder retry is not configured")
        raise HTTPException(status_code=503, detail="Muse Wonder retry is not configured. Set LLM_RETRY_API_KEY in the service environment.") from exc
    original_code = row["original_code"]
    messages = build_retry_messages(
        original_code=original_code, failed_patch=previous.get("code"),
        failure_kind=previous.get("failure_kind"),
        remaining_checks=previous.get("remaining_checks") or [],
        details=previous.get("verification_details"),
        findings_rows=list(enumerate(findings_data)),
    )
    completion = None
    for attempt in range(1, RETRY_TRANSPORT_ATTEMPTS + 1):
        try:
            completion = model_client.chat.completions.create(
                model=RETRY_MODEL_NAME,
                messages=messages,
                temperature=0.1,
                max_tokens=MAX_OUTPUT_TOKENS,
                timeout=RETRY_TIMEOUT_SECONDS,
            )
            break
        except (TypeError, ValueError, ValidationError, json.JSONDecodeError) as exc:
            # Bad response body after a successful HTTP round-trip — do not burn transport retries.
            logger.warning("Muse Wonder returned invalid retry JSON")
            raise HTTPException(status_code=502, detail="Retry model returned an invalid response. Please try again.") from exc
        except Exception as exc:
            logger.warning("Muse Wonder transport attempt %s/%s failed: %s", attempt, RETRY_TRANSPORT_ATTEMPTS, exc)
            if attempt < RETRY_TRANSPORT_ATTEMPTS:
                time.sleep(min(1.5 * attempt, 4.0))
                continue
            logger.exception("Muse Wonder retry failed after %s transport attempts", RETRY_TRANSPORT_ATTEMPTS)
            raise HTTPException(status_code=502, detail="Retry service temporarily unavailable. Please try again.") from exc
    try:
        retry_result = parse_retry_output(completion.choices[0].message.content or "")
    except (TypeError, ValueError, ValidationError, json.JSONDecodeError) as exc:
        logger.warning("Muse Wonder returned invalid retry JSON")
        raise HTTPException(status_code=502, detail="Retry model returned an invalid response. Please try again.") from exc
    if retry_result.unable_to_fix or not (retry_result.consolidated_patch or "").strip():
        consolidated = ConsolidatedPatch(code=previous.get("code"), diff=previous.get("diff") or "", change_summary=retry_result.change_summary, verification_status="not_checked", failure_kind="model_no_patch", verification_details=retry_result.unable_reason or "Muse Wonder could not produce a reliable patch.", retry_count=retry_count + 1)
    else:
        consolidated = verify_consolidated_patch(retry_result.consolidated_patch, original_code, row.get("original_detector_checks"), ENABLE_SLITHER, retry_result.change_summary, retry_count + 1, original_high_medium_checks=row.get("original_high_medium_checks") or [])
        consolidated.retry_count = retry_count + 1
    new_count = retry_count + 1
    still_failed = not consolidated.patch_verified and (consolidated.failure_kind or "") in {
        "still_vulnerable", "compile_failed", "regression_introduced",
        "surface_removed", "gutted_function", "model_no_patch",
    }
    more_retries = bool(RETRY_API_KEY) and still_failed and new_count < MAX_PATCH_RETRIES
    consolidated.retry_count = new_count
    consolidated.retry_available = more_retries
    row["consolidated_patch"] = consolidated.model_dump()
    row["retry_count"] = new_count
    update_analysis(analysis_id, row)
    f1_ran = row.get("slither_error") is None
    return AuditResponse(summary=row.get("summary") or "", findings=[Finding.model_validate(f) for f in findings_data], consolidated_patch=consolidated, meta={
        "analysis_id": analysis_id, "model": RETRY_MODEL_NAME, "retry_model": RETRY_MODEL_NAME,
        "slither_available": is_slither_available(), "slither_enabled": ENABLE_SLITHER,
        "slither_error": row.get("slither_error"), "f1_ran": f1_ran,
        "pipeline_label": "Muse Wonder → F3 verification" if f1_ran else MODEL_ONLY_PIPELINE,
        "patches_verified_count": int(consolidated.patch_verified),
        "patches_proposed_count": int(bool(consolidated.code)),
        "patches_failed_count": int(consolidated.verification_status == "failed"),
        "retry_count": new_count, "max_patch_retries": MAX_PATCH_RETRIES,
        "retry_available": more_retries, "is_retry": True,
    })


